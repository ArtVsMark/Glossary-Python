#!/usr/bin/env python3
"""У изменения ровно три ответа задаче, и четвёртого — промолчать — нет.

Правило каталога 173: изменение, отвечающее задаче, либо **закрывает** её
целиком, либо делает **часть** и называет остаток, либо **освобождено** строкой
с причиной. Слить и промолчать — не ответ: задача остаётся открытой при сделанной
работе либо закрытой при несделанной, и узнать это можно, лишь читая обе.

ЗАМЕР, ИЗ-ЗА КОТОРОГО ГЕЙТ ЗАВЕДЁН. Прежний ответ проекта по правилу гласил
«трекера у проекта нет, связи изменения с задачей ничем не проверяется». Первая
половина была неверна: задача «Правила каталога: входящие» заведена 5 сентября
и по ней ведётся вся работа. Вторая была верна, и здесь она перестаёт быть.

ФОРМА «ЗАКРЫВАЕТ» — только те слова, которые площадка исполняет
(``Closes``/``Fixes``/``Resolves``). Русское «Закрывает #25» читается человеком
как обещание закрыть, а площадкой не читается вовсе: задача осталась бы
открытой при зелёном гейте — ровно тот четвёртый ответ, против которого правило.

РАЗБОР НАДВОЕ (правило 182). Полон ли названный остаток — суждение, и машинной
эта половина не станет. **Что ответ дан и он один из трёх** — следует из тела
изменения целиком, и держится здесь.

ЧЕГО ГЕЙТ НЕ ЛОВИТ, названо здесь, а не подразумевается (правило 056):

* **судьбу задачи ПОСЛЕ слияния.** Вторая половина правила — что закрытая
  закрыта, а частичная несёт остаток — механизмом здесь не держится: закрытие
  исполняет площадка, остаток не проверяет никто;
* **верность номера.** Ссылка на несуществующую или чужую задачу пройдёт: гейт
  видит форму ответа, а не задачу;
* **правдивость освобождения.** «Без задачи: инфраструктура» гейт примет,
  как и любую другую причину: он требует, чтобы причина была названа.

Запуск::

    PR_BODY="$(cat body.md)" python scripts/check_pr_link.py
    python scripts/check_pr_link.py --from-env ДРУГАЯ_ПЕРЕМЕННАЯ

Исходы: 0 — ответ дан; 1 — ответа нет; 2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from typing import Final, NamedTuple

DEFAULT_ENV: Final = "PR_BODY"

CLOSES: Final = re.compile(r"\b(?:Closes|Fixes|Resolves)\s+#\d+", re.IGNORECASE)
"""Слова, которые площадка исполняет сама. Другие обещают и не делают."""

PART: Final = re.compile(r"Часть\s+#\d+")
REMAINDER: Final = re.compile(r"Остат|остаётся|осталось|остальн")
EXEMPT: Final = re.compile(r"Без задачи:\s*(?P<reason>\S.*)")

NOT_RUN: Final = 2
"""Проверка не отработала. Не означает «ответ дан» — его не смотрели."""


class Answer(NamedTuple):
    """Ответ изменения задаче.

    Attributes:
        kind: Какой из трёх ответов дан; пусто — ответа нет.
        detail: Чем именно ответ подтверждён.
    """

    kind: str
    detail: str


def paragraphs(body: str) -> list[str]:
    """Окна разбора: абзац, а не предложение (правило 144).

    Резать по точке нельзя — она стоит внутри имён и номеров.

    Args:
        body: Тело изменения.

    Returns:
        Абзацы одной строкой каждый.
    """
    return [" ".join(part.split()) for part in re.split(r"\n\s*\n", body) if part.strip()]


def answer(body: str) -> Answer | None:
    """Какой из трёх ответов дан в теле изменения.

    Args:
        body: Тело изменения.

    Returns:
        Ответ либо ``None``, если ответа нет.
    """
    closes = CLOSES.search(body)
    if closes:
        return Answer("закрывает", closes.group(0))

    for window in paragraphs(body):
        part = PART.search(window)
        if part and REMAINDER.search(window):
            return Answer("часть", part.group(0))

    exempt = EXEMPT.search(body)
    if exempt:
        return Answer("освобождено", exempt.group("reason").strip())

    return None


def complaint(body: str) -> str:
    """Чего именно не хватает телу изменения.

    Args:
        body: Тело изменения.

    Returns:
        Готовая к печати причина отказа.
    """
    if PART.search(body):
        return (
            "«Часть #N» есть, а остаток не назван. Частичное изменение обязано "
            "сказать, ЧТО ещё не сделано, — иначе задача выглядит закрытой "
            "работой, которой в ней нет (правило 173)"
        )
    return (
        "изменение не отвечает задаче ни одним из трёх способов. Допустимы: "
        "«Closes #N» (площадка закроет сама), «Часть #N» с названным остатком, "
        "«Без задачи: причина». Четвёртого ответа — слить и промолчать — нет"
    )


def main(argv: list[str] | None = None) -> int:
    """Точка входа.

    Args:
        argv: Аргументы командной строки; ``None`` — взять из ``sys.argv``.

    Returns:
        Код возврата процесса.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--from-env",
        default=DEFAULT_ENV,
        help="переменная окружения с телом изменения",
    )
    args = parser.parse_args(argv)

    # Тело приходит переменной окружения, а не аргументом: подстановка чужого
    # текста в командную строку — это разбор кавычек чужими руками (013).
    body = os.environ.get(args.from_env)
    if body is None:
        print(
            f"проверка не отработала: переменной {args.from_env} нет в окружении — "
            "тело изменения читать неоткуда",
            file=sys.stderr,
        )
        return NOT_RUN

    found = answer(body)
    if found is None:
        print(f"связь изменения с задачей не названа: {complaint(body)}", file=sys.stderr)
        return 1

    print(f"ответ задаче дан — {found.kind}: {found.detail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
