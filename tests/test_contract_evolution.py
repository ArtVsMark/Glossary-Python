"""Контракт описывает правила собственной эволюции: правило каталога 113.

Перечислить поля мало. Контракт обязан сказать, **что в нём стабильно, что
расширяемо и как добавляют новое** — иначе каждое изменение превращается в
переговоры с нуля, а потребители расходятся молча.

РАЗБОР НАДВОЕ (правило 182). Верны ли объявленные правила — суждение, и оно
машинным не станет. **Что они написаны и что написаны про КАЖДЫЙ контракт** —
следует из дерева целиком, и держится здесь.

ПОЧЕМУ СПИСОК КОНТРАКТОВ БЕРЁТСЯ У ПРОГОНА, А НЕ ПЕРЕЧИСЛЯЕТСЯ ЗДЕСЬ. Второй
список разошёлся бы с первым молча: новый контракт появился бы в публикации и
не появился бы в требовании описать его. Поэтому набор читает то, что прогон
публикации кладёт в каталог значков, и требует раздела на каждый файл
(правило 022).
"""

from __future__ import annotations

import re
from typing import Final

import pytest

from glossary.loader import project_root

ROOT = project_root()
DOCUMENT = ROOT / "docs" / "contracts.md"
BADGES = ROOT / ".github" / "workflows" / "badges.yml"

PUBLISHED = re.compile(r"\.github/badges/([\w.-]+)\.json")
SECTION = re.compile(r"^## +(.+)$", re.MULTILINE)

REQUIRED: Final = ("Стабильно", "Расширяемо", "Как добавляют новое")
"""Три части, без которых описание контракта неполно (правило 113).

Проверяется присутствие частей, а не их верность: машина держит то, что вопрос
задан, — судить об ответе она не может (правило 182).
"""

COMMON: Final = "Общие правила эволюции"
"""Раздел, в котором части названы один раз на все контракты.

Требовать все три части в КАЖДОМ разделе значило бы требовать копипасты, а
копия расходится с оригиналом на первой же правке (правило 090). Поэтому части
обязательны в общем разделе, а у каждого контракта обязателен свой раздел.
"""


def published() -> set[str]:
    """Имена файлов, которые публикующий прогон кладёт наружу."""
    return set(PUBLISHED.findall(BADGES.read_text(encoding="utf-8")))


def sections() -> list[str]:
    """Заголовки второго уровня целиком — с именем контракта и пояснением.

    Заголовок здесь имеет вид «`имя.json` — о чём файл»: имя обязательно,
    пояснение желательно. Вырезать из него одно только имя значило бы завести
    правило оформления заголовков там, где нужен всего лишь поиск имени.
    """
    return [title.strip() for title in SECTION.findall(DOCUMENT.read_text("utf-8"))]


def section_body(name: str) -> str:
    """Текст раздела, в заголовке которого встречается имя.

    Args:
        name: Имя контракта или заголовок раздела.

    Returns:
        Текст раздела до следующего заголовка того же уровня; пустая строка —
        такого раздела нет.
    """
    parts = re.split(r"^## ", DOCUMENT.read_text(encoding="utf-8"), flags=re.MULTILINE)
    for part in parts[1:]:
        heading = part.splitlines()[0]
        if name in heading:
            return part
    return ""


def test_document_exists():
    assert DOCUMENT.exists(), (
        f"нет {DOCUMENT.name}: правила эволюции контрактов не объявлены, и "
        "каждое изменение станет переговорами с нуля"
    )


def test_something_is_published():
    """У гейта должен быть предмет: наружу ничего не идёт — это не гейт (075)."""
    assert published(), (
        f"{BADGES.name} не публикует ни одного контракта — требовать описания нечему"
    )


@pytest.mark.parametrize("part", REQUIRED)
def test_common_rules_name_every_part(part: str):
    """Три части названы один раз на все контракты — и все три обязательны."""
    body = section_body(COMMON)
    assert body, f"в документе нет раздела «{COMMON}»"
    assert part in body, (
        f"в общих правилах эволюции не сказано «{part}» — описание контракта "
        "неполно ровно на эту часть (правило 113)"
    )


def described(name: str) -> bool:
    """Есть ли у файла свой раздел: имя встречается в заголовке."""
    return any(f"{name}.json" in heading for heading in sections())


def test_every_published_contract_has_a_section():
    """Новый контракт без раздела — обещание описать его когда-нибудь."""
    missing = sorted(name for name in published() if not described(name))
    assert not missing, (
        "публикуется контракт, у которого нет раздела в docs/contracts.md: "
        + ", ".join(missing)
    )


def test_the_data_snapshot_is_described_too():
    """Снимок наружу не публикуется, но читается машиной — правила те же."""
    assert described("data/glossary"), (
        "снимок data/glossary.json не описан: он производный, но машиночитаемый"
    )


def test_every_section_says_what_is_not_promised():
    """Вторая половина описания нужнее первой (правило 056).

    Контракт, не сказавший, чего он НЕ обещает, читается как обещающий всё.
    Проверяется на общем разделе: там граница названа один раз для всех.
    """
    assert "не обещают" in section_body(COMMON), (
        "общие правила не говорят, чего контракт не обещает"
    )


