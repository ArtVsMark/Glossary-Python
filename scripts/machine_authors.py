"""Машинные авторы изменений: кому гейты связи с задачей и журнала не пишут.

Гейт связи с задачей (``scripts/check_pr_link.py``) и гейт журнала
(``scripts/check_journal.py``) спрашивают с изменения ответ, который пишет
человек или окно: какой задаче оно отвечает и какое решение за ним стоит.
Обновлятель зависимостей ни того, ни другого написать не может, и его
изменения застревали на обоих гейтах навсегда — 2 октября так встали #54 и #55,
и их пришлось перевозить своим изменением (#67).

Освобождение называет автора и причину, а не снимает гейт: список закрытый,
пополняется явным изменением, и каждое освобождение печатается вслух. Решение
владельца 2 октября.

Граница названа: автор узнаётся по имени, которое ставит площадка, — коммиту и
изменению. Изменение, где рядом с ботом коммитил человек, освобождения не
получает: решение там уже есть, и записать его есть кому.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from collections.abc import Iterable

MACHINE: Final = {
    "dependabot[bot]": (
        "обновляет версии зависимостей и действий; задачи и решения за таким "
        "изменением нет, и написать ответ ему не о чем"
    ),
}
"""Машинный автор → почему гейтам связи и журнала с него нечего спросить."""


def exemption(authors: Iterable[str]) -> str | None:
    """Причина освобождения, если все авторы машинные; иначе ``None``.

    Args:
        authors: Имена авторов изменения — его коммитов или самого изменения.

    Returns:
        Строка «кто — почему» либо ``None``: авторов нет или среди них есть
        не машинный.
    """
    names = {name for name in authors if name}
    if not names or not names <= MACHINE.keys():
        return None
    return "; ".join(f"{name} — {MACHINE[name]}" for name in sorted(names))
