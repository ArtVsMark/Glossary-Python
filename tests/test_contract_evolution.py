def test_publication_list_is_read_from_the_workflow():
    """Список контрактов берётся у прогона: второй список разошёлся бы молча."""
    assert PUBLISHED.findall("-o .github/badges/objections.json") == ["objections"]
    assert PUBLISHED.findall("никаких файлов тут нет") == []


def test_missing_section_is_noticed():
    """Предмет, который гейт обязан отвергнуть, и тот, который обязан пропустить."""
    assert not described("выдуманный-контракт")
    assert described("objections"), "существующий раздел обязан находиться"
