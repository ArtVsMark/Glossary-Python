#!/bin/sh
# Сторож окна перед командой оболочки: правила каталога 012 и 013
# (scripts/window_guard.py), интерпретатором планки (правило 217).
#
# ПОЧЕМУ НЕ СИСТЕМНЫЙ python3. Хук исполняется в окружении процесса окна, а
# не в PATH, который хук старта выставил командам. Системный python3 там бывает
# 3.11, а на macOS — 3.9: сторож на нём мог упасть, а ненулевой код, кроме 2,
# площадка считает НЕблокирующей ошибкой — действие прошло бы непроверенным
# молча (Glossary-Python#274; у каталога тот же случай — его #869, #877).
#
# ИНТЕРПРЕТАТОР ПЛАНКИ — python<планка> на PATH либо .venv, собранный на ней.
dir="${CLAUDE_PROJECT_DIR:-.}"
. "$dir/.claude/hooks/floor.sh"
floor=$(planka_floor "$dir/pyproject.toml")
py=""
if [ -n "$floor" ]; then
  py=$(command -v "python$floor" 2>/dev/null)
  venv="$dir/.venv/bin/python"
  if [ -z "$py" ] && [ -x "$venv" ] \
    && [ "$("$venv" -c 'import sys; print("%d.%d" % sys.version_info[:2])' 2>/dev/null)" = "$floor" ]; then
    py="$venv"
  fi
fi
if [ -n "$py" ]; then
  exec "$py" "$dir/scripts/window_guard.py"
fi
# НЕТ ИНТЕРПРЕТАТОРА ПЛАНКИ — ЗАКРЫТО ТО, ЧТО СТОРОЖ СТЕРЕЖЁТ, ОСТАЛЬНОЕ ОТКРЫТО.
# Закрыть все команды значило бы обездвижить окно из-за сбоя сети при старте.
# Закрывается код 2 — «отвергнуть» по протоколу хука. ГРАНИЦА: разбор грубее
# стража и смотрит весь вход события, а не одну команду, поэтому лишне закроет
# команду, где слова git и push стоят порознь, или любую с `<<`; ошибка возможна
# только в сторону закрытия. Косвенный толчок (`c=push; git $c`) не виден.
input=$(cat)
case "$input" in
  *git*push* | *"<<"*)
    echo "сторож окна не запущен: интерпретатора планки python${floor:-?} нет — ни на PATH, ни в .venv. Толчок и heredoc закрыты до починки: без сторожа они прошли бы непроверенными. Перезапустите окно (хук старта ставит python${floor:-?}) или поставьте его вручную." >&2
    exit 2 ;;
esac
exit 0
