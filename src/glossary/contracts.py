"""Общая обёртка публикуемых контрактов.

Витрина публикует четыре файла — факты, замечания, покрытие, разность версий, —
и у всех четырёх одна шапка: кто издал, о чём файл, какой он версии и когда
собран. Четыре копии этой шапки разъехались бы на первой же правке, поэтому она
здесь одна.

**Версия — строка, а не число.** Численная форма не различает ``1.0`` и
``1.10``, а в экосистеме уже четыре разных ``schema``; читателю пришлось бы
знать два диалекта (просьба соседа, Glossary-Python#18).

**Отметка времени есть, и это пересмотренное решение.** Сначала её здесь не
было: она меняет файл на каждом прогоне, а публикующий прогон именно на
неизменность и смотрит, решая, коммитить ли. Довод потребителя оказался
сильнее: файл **не исчезает, когда прогон ломается**, — он остаётся вчерашним,
и снаружи это неотличимо от «ничего не менялось». Без отметки потребитель
показывает прошлое как настоящее сколько угодно долго; с ней у него есть право
сказать «данные устарели». Лишний коммит на прогон — приемлемая цена за то,
чтобы молчаливое враньё стало невозможным.

Отпечаток снимка отметку не заменяет: он отвечает на «о каком снимке речь», а
не на «свежий ли он». Вопроса два, и ответов тоже два.
"""

from __future__ import annotations

import datetime as dt
from typing import Any, Final

__all__ = ["PRODUCER", "SCHEMA", "SOURCE", "envelope", "now"]

SCHEMA: Final = "1.0"
"""Версия формата публикуемых контрактов. Строкой — см. модуль."""

PRODUCER: Final = "ArtVsMark/Glossary-Python"
"""Кто издал файл."""

SOURCE: Final = "ArtVsMark/Stepik-Python-Grader"
"""Чьё содержание описано. Карточки правятся там, не здесь."""


def now() -> str:
    """Текущий момент в ISO 8601 с поясом.

    Пояс обязателен: время без него читается получателем в его собственном
    поясе, и «два часа назад» превращается в «через пять часов».
    """
    return dt.datetime.now(dt.UTC).isoformat(timespec="seconds")


def envelope(schema_of: str) -> dict[str, Any]:
    """Шапка контракта: кто, о чём, какой версии и когда собрал."""
    return {
        "schema": SCHEMA,
        "schema_of": schema_of,
        "producer": PRODUCER,
        "source": SOURCE,
        "generated_at": now(),
    }
