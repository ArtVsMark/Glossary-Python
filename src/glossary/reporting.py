"""Общее для отчётов: обрезка выдачи, которая не умеет быть молчаливой.

Правило каталога 016: урезанный результат обязан сообщать, что он урезан, и
насколько. Иначе полный ответ и обрезанный выглядят одинаково, а различить их
можно, только зная ожидаемый объём — то есть уже имея то, чего нет.

Помощник живёт здесь, а не в каждом отчёте, по правилу 090: у проекта два
модуля с ограничением выдачи — :mod:`glossary.objections` и
:mod:`glossary.completeness`, — и три места, где список резался. Все три писали
одну и ту же строку своими руками, то есть четвёртое место могло написать её
иначе или не написать вовсе.

Здесь срез и маркер обрыва отдаются **одним вызовом**: показать урезанное, не
получив маркера, нельзя — не потому, что это запрещено, а потому, что негде.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Final, TypeVar

if TYPE_CHECKING:
    from collections.abc import Sequence

__all__ = ["FULL_LIST_HINT", "truncate"]

T = TypeVar("T")

FULL_LIST_HINT: Final = "Полный список: `--limit 0`."
"""Как получить невырезанное. Маркер обрыва без этого — тупик для читателя."""


def truncate(items: Sequence[T], limit: int) -> tuple[list[T], list[str]]:
    """Урезать список и назвать обрыв.

    Args:
        items: Полный список.
        limit: Сколько показать; ноль и меньше — показать всё.

    Returns:
        Пара «что показать» и строки маркера обрыва для Markdown-отчёта.
        Маркер пуст, когда обрыва не было: молчание тут означает «показано
        всё», и это единственный случай, когда оно так означает.
    """
    if limit <= 0 or len(items) <= limit:
        return list(items), []
    hidden = len(items) - limit
    return list(items[:limit]), ["", f"…и ещё {hidden}. {FULL_LIST_HINT}"]
